#!/usr/bin/env bash
# Optional developer-only local Cargo patch. Never invoked by the public default build.
set -euo pipefail
repo_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)
config_path="$repo_root/artifacts/private-agent.toml"
discovered_config="$repo_root/.cargo/config.toml"
lock_dir="$repo_root/artifacts/private-agent-running"
usage() {
  cat <<'USAGE'
Usage:
  scripts/private-agent.sh configure ../pocket-finance-agent
  scripts/private-agent.sh cargo check -p pocket-finance-android
  scripts/private-agent.sh run scripts/android-env.sh npm run tauri -- android build --debug --target aarch64 --apk --ci
  scripts/private-agent.sh disable

configure accepts a local private checkout path, relative to your current directory.
Only cargo/run subcommands use the override. Ordinary Cargo builds use the public stub.
Do not run another Cargo command in this checkout while the wrapper is running.
USAGE
}
case "${1:-}" in
  configure)
    if [[ $# != 2 ]]; then usage >&2; exit 2; fi
    if [[ -d "$lock_dir" ]]; then echo "A private Cargo operation is already running." >&2; exit 1; fi
    checkout=$(cd -- "$2" && pwd -P)
    provider_path="$checkout/crates/pocket-category-provider"
    if [[ ! -f "$provider_path/Cargo.toml" ]]; then
      echo "The checkout does not contain crates/pocket-category-provider/Cargo.toml." >&2; exit 1
    fi
    if [[ "$provider_path" =~ [[:cntrl:]] ]]; then
      echo "The local path must not contain control characters." >&2; exit 1
    fi
    # TOML basic-string escaping, including paths containing spaces or quotes.
    escaped_path=${provider_path//\\/\\\\}
    escaped_path=${escaped_path//\"/\\\"}
    mkdir -p -- "$repo_root/artifacts"
    printf '# Generated by scripts/private-agent.sh; local-only.\n[patch.crates-io]\npocket-category-provider = { path = "%s" }\n' "$escaped_path" > "$config_path"
    echo "Configured artifacts/private-agent.toml. Use this script's cargo/run subcommands to opt in."
    ;;
  cargo|run)
    operation=$1
    shift
    if [[ $# == 0 ]]; then usage >&2; exit 2; fi
    if [[ ! -f "$config_path" ]]; then echo "Run the configure command first." >&2; exit 1; fi
    if [[ "$operation" == run && ( -e "$discovered_config" || -L "$discovered_config" || -e "$repo_root/.cargo/config" || -L "$repo_root/.cargo/config" ) ]]; then
      echo "run requires no existing .cargo/config or .cargo/config.toml; existing configuration is preserved." >&2
      echo "Use the cargo subcommand for explicit Cargo invocations with existing configuration." >&2
      exit 1
    fi
    if ! mkdir -- "$lock_dir" 2>/dev/null; then
      echo "Another private Cargo operation is running (or left artifacts/private-agent-running)." >&2; exit 1
    fi
    # A private dependency graph changes Cargo.lock. Keep it out of public commits.
    had_lock=0
    temporary_config=0
    if [[ -f "$repo_root/Cargo.lock" ]]; then
      had_lock=1
      cp -- "$repo_root/Cargo.lock" "$lock_dir/Cargo.lock"
    fi
    cleanup() {
      command_status=$?
      trap - EXIT INT TERM
      if [[ $temporary_config == 1 ]]; then rm -f -- "$discovered_config"; fi
      if [[ $had_lock == 1 ]]; then
        cp -- "$lock_dir/Cargo.lock" "$repo_root/Cargo.lock"
      else
        rm -f -- "$repo_root/Cargo.lock"
      fi
      rm -rf -- "$lock_dir"
      exit "$command_status"
    }
    trap cleanup EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    cd -- "$repo_root"
    if [[ "$operation" == run ]]; then
      mkdir -p -- "$repo_root/.cargo"
      temporary_config=1
      cp -- "$config_path" "$discovered_config"
      "$@"
    else
      cargo --config "$config_path" "$@"
    fi
    ;;
  disable)
    if [[ $# != 1 ]]; then usage >&2; exit 2; fi
    if [[ -d "$lock_dir" ]]; then echo "A private Cargo operation is already running." >&2; exit 1; fi
    rm -f -- "$config_path"
    echo "Removed the optional patch configuration."
    ;;
  -h|--help|help) usage ;;
  *) usage >&2; exit 2 ;;
esac
