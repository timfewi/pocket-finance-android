#!/usr/bin/env node
// Package a public CI build only. Never point this at a private-provider APK.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';

const tag = process.argv[2];
if (!/^v\d+\.\d+\.\d+-alpha\.\d+$/.test(tag ?? '')) {
  throw new Error('Expected an alpha release tag, such as v0.1.0-alpha.1');
}
if (!process.env.ANDROID_HOME || !process.env.JAVA_HOME) {
  throw new Error('Set ANDROID_HOME and JAVA_HOME to the build toolchain');
}
const run = (command, args) => execFileSync(command, args, {
  encoding: 'utf8', maxBuffer: 16 * 1024 * 1024,
}).trim();
const metadata = JSON.parse(run('cargo', ['metadata', '--locked', '--format-version', '1', '--filter-platform', 'aarch64-linux-android']));
const provider = metadata.packages.find((entry) => entry.name === 'pocket-category-provider');
if (provider?.manifest_path !== resolve('crates/category-provider/Cargo.toml') ||
    metadata.packages.some((entry) => ['agent-core', 'gguf-backend', 'finance-contracts'].includes(entry.name))) {
  throw new Error('Publication requires the public no-model category provider');
}
const apk = process.argv[3] ?? 'src-tauri/gen/android/app/build/outputs/apk/universal/debug/app-universal-debug.apk';
const buildTools = join(process.env.ANDROID_HOME, 'build-tools/36.0.0');
const signature = run(join(buildTools, 'apksigner'), ['verify', '--verbose', '--print-certs', apk]);
if (!signature.includes('Verified using v2 scheme (APK Signature Scheme v2): true')) {
  throw new Error('APK v2 signature verification failed');
}
const certificate = signature.match(/Signer #1 certificate SHA-256 digest: ([a-f0-9]{64})/)?.[1];
if (!certificate) throw new Error('Missing signing certificate fingerprint');
run(join(buildTools, 'zipalign'), ['-c', '-P', '16', '4', apk]);
const badging = run(join(buildTools, 'aapt'), ['dump', 'badging', apk]);
if (badging.match(/^native-code: (.+)$/m)?.[1] !== "'arm64-v8a'" ||
    !badging.includes("package: name='io.github.timfewi.pocketfinance'")) {
  throw new Error('Unexpected application or native architecture');
}
const sourceCommit = run('git', ['rev-parse', 'HEAD']);
if (process.env.GITHUB_SHA && process.env.GITHUB_SHA !== sourceCommit) {
  throw new Error('Checkout does not match the workflow commit');
}
const repository = 'timfewi/pocket-finance-android';
const filename = 'pocket-finance-public-arm64-debug.apk';
const size = statSync(apk).size;
const sha256 = createHash('sha256').update(readFileSync(apk)).digest('hex');
const output = 'artifacts/release';
mkdirSync(output, { recursive: true });
copyFileSync(apk, join(output, filename));
writeFileSync(join(output, 'SHA256SUMS'), `${sha256}  ${filename}\n`);
const info = {
  schema_version: 1,
  release: tag,
  source_repository: `https://github.com/${repository}`,
  source_commit: sourceCommit,
  workflow_run: process.env.GITHUB_RUN_ID ? `https://github.com/${repository}/actions/runs/${process.env.GITHUB_RUN_ID}` : null,
  artifact: { filename, size_bytes: size, sha256, signer_certificate_sha256: certificate },
  build_command: 'scripts/android-env.sh npm run tauri -- android build --debug --target aarch64 --apk --ci',
  rust: run('rustc', ['--version']),
  tauri_cli: run('node_modules/.bin/tauri', ['--version']),
  sdk_api: 36,
  build_tools: '36.0.0',
  ndk: '29.0.14206865',
  architecture: 'arm64-v8a',
  minimum_android_api: 24,
  provider: 'public no-model fallback',
  signature_v2_verified: true,
  zip_alignment_16k_verified: true,
  physical_device_tested: false,
  limitations: [
    'Development signing key generated by the build runner; no stable production signing identity.',
    'Debuggable alpha build retains Internet and network-state permissions.',
    'No private finance-agent implementation or Qwen weights/runtime included.',
    'Camera, actual OCR, installation and first-launch airplane mode remain unverified on a device.',
  ],
};
writeFileSync(join(output, 'BUILDINFO.json'), `${JSON.stringify(info, null, 2)}\n`);
writeFileSync(join(output, 'release.md'), `Public **alpha test APK** for the receipt workflow: photograph or import a receipt, recognize Latin text with bundled on-device OCR, review the fields, and explicitly save an expense locally.

The mobile-first interface uses bottom navigation for overview, capture and receipts,
preserves edits when switching sections, and expands to a sidebar on wider screens.
Android applies system-bar/cutout/keyboard insets to the WebView; actual Seeker
keyboard and layout behavior still need device verification.

### Download and install

- Download **${filename}** below (${size.toLocaleString('en-US')} bytes; approximately ${Math.ceil(size / 1_000_000)} MB).
- ARM64 Android 7.0+ (API 24), including the architecture used by the Solana Seeker.
- Open the APK on the phone and allow installation from that browser when Android prompts. No build tools or private repository access are required.
- Use synthetic receipts. Enable airplane mode **before first launch** for the offline acceptance test.

### Verification and limitations

This APK was built from the public source in GitHub Actions. Public Rust tests and frontend checks ran before the Android build; native receipt-file and viewport-inset JVM tests ran after it. The APK v2 signature and 16 KiB ZIP alignment were verified. Synthetic browser tests confirmed that a 12,49 EUR total, 20,00 EUR cash tendered and 7,51 EUR change save exactly 1249 cents; see the [verification report](https://github.com/${repository}/blob/${sourceCommit}/docs/VERIFICATION.md) and [mobile-first checks](https://github.com/${repository}/blob/${sourceCommit}/docs/MOBILE-FIRST.md).

**No physical phone was available:** installation, camera, actual OCR and first-launch airplane mode remain unverified. This is a development-signed, debuggable test build and retains Internet/network-state permissions. The runner generates a development signing key; this is not a stable production signing identity. Installing over a differently signed build may require uninstalling that app, which deletes its local data.

Bundled ML Kit Latin OCR uses Google's SDK terms. No Qwen weights or private agent implementation are included; categories remain manually selectable. The private agent repository remains private.

### Integrity and source

Download SHA256SUMS beside the APK and run:

\`\`\`sh
sha256sum -c SHA256SUMS
\`\`\`

APK SHA-256: \`${sha256}\`.

Source: [\`${sourceCommit.slice(0, 7)}\`](https://github.com/${repository}/commit/${sourceCommit}). BUILDINFO.json records the build run, checksum and signing certificate. This CI artifact has its own checksum and certificate; it is distinct from the earlier locally built APKs documented in the repository.

See the [Android instructions](https://github.com/${repository}/blob/${sourceCommit}/docs/ANDROID.md).
`);
console.log(JSON.stringify({ filename, size_bytes: size, sha256, source_commit: sourceCommit }));
